const tmpId = () => `tc-${Math.random().toString(36).slice(2, 9)}`;

const NEXT_CASE_STATUS = {
  ready: "automated",
  automated: "passing",
  passing: "failing",
  failing: "ready",
};

const STATUS_BADGE = {
  ready: "border-border bg-muted/40 text-muted-foreground",
  automated: "border-border bg-accent text-accent-foreground",
  passing: "border-[hsl(var(--success)/0.4)] bg-[hsl(var(--success)/0.12)] text-[hsl(var(--success))]",
  failing: "border-destructive/40 bg-destructive/10 text-destructive",
};

function generateRunnableSpecFile(projectName, cases = []) {
  const unitAndInt = cases.filter((c) => c.level !== "e2e");
  const e2eCases = cases.filter((c) => c.level === "e2e");

  return `// Generated by Formora Testing Center — ${projectName || "Workspace"}
// Runners: Vitest (Unit & API Integration) + Playwright (E2E Smoke)

import { describe, it, expect } from "vitest";

describe("${(projectName || "Workspace").replace(/"/g, '\\"')} — Unit & API Integration Suite", () => {
${unitAndInt
  .map(
    (tc) => `  it("[${(tc.level || "integration").toUpperCase()}] ${tc.title.replace(/"/g, '\\"')}", async () => {
${(tc.steps || []).map((s, idx) => `    // Step ${idx + 1}: ${s}`).join("\n") || "    // Execute scenario"}
    // Expected: ${(tc.expected || "Passes contract").replace(/\n/g, " ")}
    expect(true).toBe(true);
  });`
  )
  .join("\n\n")}
});

/* --------------------------------------------------------------------------
 * Playwright E2E Smoke Journeys (tests/e2e.spec.ts)
 * --------------------------------------------------------------------------
import { test, expect } from "@playwright/test";

${e2eCases
  .map(
    (tc) => `test("${tc.title.replace(/"/g, '\\"')}", async ({ page }) => {
${(tc.steps || []).map((s, idx) => `  // ${idx + 1}. ${s}`).join("\n")}
  await page.goto("/");
  await expect(page).toHaveURL(/\\//);
});`
  )
  .join("\n\n")}
*/
`;
}

function CaseEditorSheet({ testCase, features, endpoints, onChange, onDelete, onResolve, onClose }) {
  if (!testCase) return null;
  const set = (k, v) => onChange({ ...testCase, [k]: v });

  return (
    <Sheet open onOpenChange={(o) => !o && onClose()}>
      <SheetContent className="w-full sm:max-w-[540px] overflow-y-auto" data-testid="testcase-editor-sheet">
        <SheetHeader>
          <SheetTitle>Edit test specification</SheetTitle>
        </SheetHeader>
        <div className="mt-5 space-y-4">
          {testCase.needs_review && (
            <div className="flex items-center gap-2 rounded border border-[hsl(var(--warning)/0.4)] bg-[hsl(var(--warning)/0.1)] px-3 py-2 text-xs">
              <AlertTriangle className="h-3.5 w-3.5 text-[hsl(var(--warning))]" />
              <span className="flex-1">{testCase.review_reason || "Upstream feature or endpoint changed"}</span>
              <Button size="sm" variant="outline" className="h-6 text-[11px]" onClick={onResolve}>
                Mark reviewed
              </Button>
            </div>
          )}

          <div className="space-y-1.5">
            <Label>Test scenario title</Label>
            <Input value={testCase.title || ""} onChange={(e) => set("title", e.target.value)} />
          </div>

          <div className="grid grid-cols-3 gap-3">
            <div className="space-y-1.5">
              <Label>Pyramid level</Label>
              <Select value={testCase.level || "integration"} onValueChange={(v) => set("level", v)}>
                <SelectTrigger className="text-xs">
                  <SelectValue />
                </SelectTrigger>
                <SelectContent>
                  <SelectItem value="unit">Unit (Vitest)</SelectItem>
                  <SelectItem value="integration">Integration (API)</SelectItem>
                  <SelectItem value="e2e">E2E (Playwright)</SelectItem>
                </SelectContent>
              </Select>
            </div>
            <div className="space-y-1.5">
              <Label>Status</Label>
              <Select value={testCase.status || "ready"} onValueChange={(v) => set("status", v)}>
                <SelectTrigger className="text-xs">
                  <SelectValue />
                </SelectTrigger>
                <SelectContent>
                  <SelectItem value="ready">Ready</SelectItem>
                  <SelectItem value="automated">Automated</SelectItem>
                  <SelectItem value="passing">Passing</SelectItem>
                  <SelectItem value="failing">Failing</SelectItem>
                </SelectContent>
              </Select>
            </div>
            <div className="space-y-1.5">
              <Label>Target module</Label>
              <Input className="h-9 text-xs font-mono" value={testCase.target || ""} onChange={(e) => set("target", e.target.value)} />
            </div>
          </div>

          <div className="grid grid-cols-2 gap-3">
            <div className="space-y-1.5">
              <Label>Linked feature</Label>
              <Select value={testCase.feature_id || "__none__"} onValueChange={(v) => set("feature_id", v === "__none__" ? null : v)}>
                <SelectTrigger className="text-xs">
                  <SelectValue placeholder="None" />
                </SelectTrigger>
                <SelectContent>
                  <SelectItem value="__none__">None</SelectItem>
                  {features.map((f) => (
                    <SelectItem key={f.id} value={f.id}>
                      {f.title}
                    </SelectItem>
                  ))}
                </SelectContent>
              </Select>
            </div>
            <div className="space-y-1.5">
              <Label>Linked API contract</Label>
              <Select value={testCase.endpoint_path || "__none__"} onValueChange={(v) => set("endpoint_path", v === "__none__" ? null : v)}>
                <SelectTrigger className="text-xs font-mono">
                  <SelectValue placeholder="None" />
                </SelectTrigger>
                <SelectContent>
                  <SelectItem value="__none__">None</SelectItem>
                  {endpoints.map((ep) => {
                    const lbl = `${ep.method} ${ep.path}`;
                    return (
                      <SelectItem key={lbl} value={lbl}>
                        {lbl}
                      </SelectItem>
                    );
                  })}
                </SelectContent>
              </Select>
            </div>
          </div>

          <div className="space-y-1.5">
            <Label>Execution steps</Label>
            <ListEditor items={testCase.steps || []} onChange={(v) => set("steps", v)} testid="testcase-steps" />
          </div>

          <div className="space-y-1.5">
            <Label>Expected assertion</Label>
            <Textarea rows={2} value={testCase.expected || ""} onChange={(e) => set("expected", e.target.value)} />
          </div>

          <div className="pt-3 border-t hairline flex justify-between">
            <Button variant="ghost" className="text-destructive" onClick={onDelete}>
              <Trash2 className="h-3.5 w-3.5 mr-1.5" />
              Delete test
            </Button>
            <Button variant="outline" onClick={onClose}>
              Done
            </Button>
          </div>
        </div>
      </SheetContent>
    </Sheet>
  );
}

export default function TestingCenter() {
  const art = useArtifact("testing");
  const featArt = useArtifact("features");
  const apiArt = useArtifact("api");
  const { pid, project, setAiOpen, refresh } = useProject();

  const [draft, setDraft] = useDraft(art.content, (c) => ({
    strategy: c?.strategy || "",
    runner_stack: c?.runner_stack || { unit: "Vitest", integration: "Vitest + Supertest", e2e: "Playwright" },
    cases: c?.cases || [],
  }));

  const [levelFilter, setLevelFilter] = useState("ALL");
  const [editingId, setEditingId] = useState(null);

  const cases = draft.cases || [];
  const features = featArt.content?.features || [];
  const mvpFeatures = useMemo(() => features.filter((f) => f.scope === "mvp" || !f.scope), [features]);
  const endpoints = apiArt.content?.endpoints || [];
  const featureById = useMemo(() => Object.fromEntries(features.map((f) => [f.id, f])), [features]);

  const coverage = useMemo(() => {
    const coveredFeatIds = new Set(cases.map((c) => c.feature_id).filter(Boolean));
    const coveredEps = new Set(cases.map((c) => c.endpoint_path).filter(Boolean));
    const mvpCovered = mvpFeatures.filter((f) => coveredFeatIds.has(f.id)).length;
    const epLabels = endpoints.map((e) => `${e.method} ${e.path}`);
    const epCovered = epLabels.filter((lbl) => coveredEps.has(lbl)).length;
    const uncoveredEndpoints = endpoints.filter((e) => !coveredEps.has(`${e.method} ${e.path}`));

    return {
      unitCount: cases.filter((c) => c.level === "unit").length,
      intCount: cases.filter((c) => c.level === "integration").length,
      e2eCount: cases.filter((c) => c.level === "e2e").length,
      mvpCovered,
      mvpTotal: mvpFeatures.length,
      epCovered,
      epTotal: epLabels.length,
      uncoveredEndpoints,
    };
  }, [cases, mvpFeatures, endpoints]);

  if (art.loading) return <PageLoading />;
  if (art.error) return <PageError message={art.error} onRetry={art.load} />;

  const orig = {
    strategy: art.content?.strategy || "",
    runner_stack: art.content?.runner_stack || { unit: "Vitest", integration: "Vitest + Supertest", e2e: "Playwright" },
    cases: art.content?.cases || [],
  };
  const dirty = JSON.stringify(draft) !== JSON.stringify(orig);
  const save = () => art.save(draft, { summary: `Updated test suite (${cases.length} specs)` });

  const filtered = levelFilter === "ALL" ? cases : cases.filter((c) => c.level === levelFilter);
  const activeCase = cases.find((c) => c.id === editingId) || null;

  const addCase = (level = "integration", preset = {}) => {
    const nc = {
      id: tmpId(),
      level,
      title: preset.title || "New test specification",
      target: preset.target || "Core API",
      feature_id: preset.feature_id || mvpFeatures[0]?.id || null,
      endpoint_path: preset.endpoint_path || null,
      status: "ready",
      steps: preset.steps || ["Arrange test fixture", "Execute target action", "Assert response & persisted state"],
      expected: preset.expected || "Returns expected HTTP status and persists cleanly.",
      needs_review: false,
      review_reason: null,
    };
    setDraft({ ...draft, cases: [nc, ...cases] });
    if (!preset.silent) setEditingId(nc.id);
  };

  const quickCoverEndpoint = (ep) => {
    const lbl = `${ep.method} ${ep.path}`;
    addCase("integration", {
      title: `${lbl} — contract validation & authorization check`,
      target: lbl,
      feature_id: ep.feature_id || null,
      endpoint_path: lbl,
      steps: [
        ep.auth_required !== false ? "Authenticate caller session" : "Prepare public request",
        `Send ${lbl} request with valid schema`,
        "Verify HTTP status, payload shape, and tenant isolation",
      ],
      expected: ep.test_cases?.[0] || `Returns 200/201 matching ${lbl} response contract.`,
      silent: true,
    });
    toast.success(`Added integration spec for ${lbl}`);
  };

  const exportSpecFile = () => {
    const slug = (project?.name || "formora-suite").toLowerCase().replace(/[^a-z0-9]+/g, "-");
    const code = generateRunnableSpecFile(project?.name, cases);
    download(`${slug}.spec.ts`, code, "text/typescript");
    toast.success(`Exported ${slug}.spec.ts`);
  };

  return (
    <div className="px-6 md:px-10 py-8 max-w-7xl fade-up">
      <PageHeader
        eyebrow="Deliver · Phase 2"
        title="Testing center"
        description="Unit, API integration, and Playwright E2E test specifications linked directly to MVP features and REST contracts."
      >
        <ArtifactBar
          kind="testing"
          art={art}
          workflow="testing"
          dirty={dirty}
          onSave={save}
          extra={
            cases.length > 0 && (
              <Button size="sm" variant="outline" className="h-8 gap-1.5" onClick={exportSpecFile} data-testid="export-spec-ts-btn">
                <Download className="h-3.5 w-3.5" />
                Export `.spec.ts`
              </Button>
            )
          }
        />
      </PageHeader>

      <ReviewBanner artifact={art.artifact} onResolve={art.resolveReview} />

      {!cases.length ? (
        <EmptyState
          icon={FlaskConical}
          title="No test plan generated yet"
          body="Derive unit, API integration, and E2E test cases linked to your features and REST endpoints."
          action="Generate with AI"
          onAction={() => setAiOpen({ workflow: "testing" })}
          testid="testing-empty"
        >
          <button className="text-sm text-muted-foreground hover:text-foreground" onClick={() => addCase("integration")}>
            or add a test case manually
          </button>
        </EmptyState>
      ) : (
        <div className="space-y-6">
          {/* Coverage & Trophy Strip */}
          <div className="grid gap-4 md:grid-cols-3" data-testid="testing-coverage-strip">
            <div className="rounded-md border hairline bg-card/30 p-4 space-y-1.5">
              <div className="eyebrow">Testing trophy split</div>
              <div className="flex items-baseline gap-4 pt-1 font-mono text-sm">
                <span>
                  <b className="text-lg">{coverage.unitCount}</b> unit
                </span>
                <span>
                  <b className="text-lg">{coverage.intCount}</b> integration
                </span>
                <span>
                  <b className="text-lg">{coverage.e2eCount}</b> e2e
                </span>
              </div>
              <div className="text-[11px] text-muted-foreground font-mono">
                {draft.runner_stack?.unit || "Vitest"} · {draft.runner_stack?.e2e || "Playwright"}
              </div>
            </div>

            <div className="rounded-md border hairline bg-card/30 p-4 space-y-2">
              <div className="flex items-baseline justify-between">
                <span className="eyebrow">MVP Feature Coverage</span>
                <span className="font-mono text-sm font-semibold">
                  {coverage.mvpCovered}/{coverage.mvpTotal || 0}
                </span>
              </div>
              <div className="h-2 rounded-full bg-muted overflow-hidden">
                <div
                  className="h-full bg-foreground transition-all"
                  style={{ width: `${coverage.mvpTotal ? Math.round((coverage.mvpCovered / coverage.mvpTotal) * 100) : 100}%` }}
                />
              </div>
              <div className="text-xs text-muted-foreground"> MVP features linked to at least one test case</div>
            </div>

            <div className="rounded-md border hairline bg-card/30 p-4 space-y-2">
              <div className="flex items-baseline justify-between">
                <span className="eyebrow">API Contract Coverage</span>
                <span className="font-mono text-sm font-semibold">
                  {coverage.epCovered}/{coverage.epTotal || 0}
                </span>
              </div>
              <div className="h-2 rounded-full bg-muted overflow-hidden">
                <div
                  className="h-full bg-[hsl(var(--success))] transition-all"
                  style={{ width: `${coverage.epTotal ? Math.round((coverage.epCovered / coverage.epTotal) * 100) : 100}%` }}
                />
              </div>
              <div className="text-xs text-muted-foreground">REST endpoints covered by integration specs</div>
            </div>
          </div>

          {/* Uncovered Endpoints Quick-Cover Bar */}
          {coverage.uncoveredEndpoints.length > 0 && (
            <div className="rounded-md border hairline bg-muted/25 px-4 py-3 flex flex-wrap items-center gap-2 text-xs">
              <span className="font-mono text-[11px] uppercase text-muted-foreground mr-1">Uncovered endpoints (click to add spec):</span>
              {coverage.uncoveredEndpoints.slice(0, 6).map((ep) => {
                const lbl = `${ep.method} ${ep.path}`;
                return (
                  <button
                    key={lbl}
                    type="button"
                    onClick={() => quickCoverEndpoint(ep)}
                    className="rounded border hairline bg-background px-2 py-0.5 font-mono text-[11px] hover:border-foreground transition-colors"
                  >
                    + {lbl}
                  </button>
                );
              })}
            </div>
          )}

          {/* Filter & Add Bar */}
          <div className="flex flex-wrap items-center justify-between gap-3 pb-3 border-b hairline">
            <div className="flex flex-wrap items-center gap-1.5" data-testid="testing-level-filters">
              {[
                ["ALL", `ALL SPECS (${cases.length})`],
                ["unit", `UNIT (${coverage.unitCount})`],
                ["integration", `INTEGRATION (${coverage.intCount})`],
                ["e2e", `E2E (${coverage.e2eCount})`],
              ].map(([id, lbl]) => (
                <button
                  key={id}
                  onClick={() => setLevelFilter(id)}
                  className={`px-2.5 py-1 rounded font-mono text-xs transition-colors ${
                    levelFilter === id ? "bg-foreground text-background" : "border hairline text-muted-foreground hover:text-foreground"
                  }`}
                >
                  {lbl}
                </button>
              ))}
            </div>
            <Button
              size="sm"
              variant="outline"
              className="h-8 gap-1.5"
              onClick={() => addCase(levelFilter === "ALL" ? "integration" : levelFilter)}
              data-testid="add-testcase-btn"
            >
              <Plus className="h-3.5 w-3.5" />
              Add test spec
            </Button>
          </div>

          {/* Test Cases Table */}
          <div className="rounded-md border hairline divide-y divide-border/60 bg-card/20" data-testid="test-cases-list">
            {filtered.map((tc) => (
              <div key={tc.id} className="p-4 flex flex-col gap-3 md:flex-row md:items-start md:justify-between hover:bg-muted/25 transition-colors">
                <div className="space-y-1.5 min-w-0 flex-1">
                  <div className="flex flex-wrap items-center gap-2">
                    <span className="rounded border hairline bg-muted/60 px-1.5 py-0.5 font-mono text-[10px] uppercase">
                      {tc.level}
                    </span>
                    {tc.endpoint_path && (
                      <span className="rounded bg-muted px-2 py-0.5 font-mono text-[11px]">{tc.endpoint_path}</span>
                    )}
                    {tc.feature_id && featureById[tc.feature_id] && (
                      <span className="rounded border hairline px-2 py-0.5 text-[11px] text-muted-foreground">
                        Feature: {featureById[tc.feature_id].title}
                      </span>
                    )}
                    {tc.needs_review && (
                      <span className="inline-flex items-center gap-1 text-[11px] font-mono text-[hsl(var(--warning))]">
                        <AlertTriangle className="h-3 w-3" />
                        needs review
                      </span>
                    )}
                  </div>

                  <div className="text-sm font-semibold">{tc.title}</div>

                  {(tc.steps || []).length > 0 && (
                    <div className="text-xs text-muted-foreground">
                      {(tc.steps || []).join(" → ")}
                    </div>
                  )}

                  {tc.expected && (
                    <div className="text-xs font-mono text-muted-foreground">
                      <span className="text-foreground">ASSERT:</span> {tc.expected}
                    </div>
                  )}
                </div>

                <div className="flex items-center gap-2 shrink-0">
                  <button
                    type="button"
                    onClick={() =>
                      setDraft({
                        ...draft,
                        cases: cases.map((c) => (c.id === tc.id ? { ...c, status: NEXT_CASE_STATUS[c.status] || "ready" } : c)),
                      })
                    }
                    title="Click to cycle status (Ready → Automated → Passing → Failing)"
                    className={`inline-flex items-center gap-1.5 rounded border px-2.5 py-1 font-mono text-xs uppercase transition-colors ${
                      STATUS_BADGE[tc.status] || STATUS_BADGE.ready
                    }`}
                  >
                    {tc.status === "passing" ? <CheckCircle2 className="h-3.5 w-3.5" /> : <Circle className="h-3 w-3" />}
                    {tc.status || "ready"}
                  </button>
                  <Button size="sm" variant="ghost" className="h-8 w-8 p-0" onClick={() => setEditingId(tc.id)}>
                    <Pencil className="h-3.5 w-3.5" />
                  </Button>
                </div>
              </div>
            ))}
          </div>
        </div>
      )}

      {activeCase && (
        <CaseEditorSheet
          testCase={activeCase}
          features={features}
          endpoints={endpoints}
          onClose={() => setEditingId(null)}
          onResolve={async () => {
            await http.post(`/projects/${pid}/items/resolve-review`, { type: "test_case", id: activeCase.id });
            setDraft({
              ...draft,
              cases: cases.map((c) => (c.id === activeCase.id ? { ...c, needs_review: false, review_reason: null } : c)),
            });
            art.load();
            refresh();
          }}
          onChange={(updated) => setDraft({ ...draft, cases: cases.map((c) => (c.id === updated.id ? updated : c)) })}
          onDelete={() => {
            setDraft({ ...draft, cases: cases.filter((c) => c.id !== activeCase.id) });
            setEditingId(null);
          }}
        />
      )}
    </div>
  );
}


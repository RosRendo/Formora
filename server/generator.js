export function validateSchema(schemaContent) {
  const entities = schemaContent?.entities || [];
  const relationships = schemaContent?.relationships || [];
  const issues = [];
  const seenTables = new Set();
  const entityMap = new Map();

  for (const ent of entities) {
    entityMap.set(ent.id, ent);
    const key = (ent.name || "").trim().toLowerCase();
    if (!key) {
      issues.push({ level: "error", entity_id: ent.id, message: "A table has an empty name." });
    } else if (seenTables.has(key)) {
      issues.push({ level: "error", entity_id: ent.id, message: `Duplicate table name "${ent.name}".` });
    }
    seenTables.add(key);

    const fields = ent.fields || [];
    if (!fields.length) {
      issues.push({ level: "error", entity_id: ent.id, message: `Table "${ent.name}" has no columns.` });
      continue;
    }
    if (!fields.some((f) => f.primary_key)) {
      issues.push({ level: "warning", entity_id: ent.id, message: `Table "${ent.name}" has no primary key column.` });
    }
    const seenCols = new Set();
    for (const f of fields) {
      const colKey = (f.name || "").trim().toLowerCase();
      if (!colKey) {
        issues.push({ level: "error", entity_id: ent.id, message: `Table "${ent.name}" has an unnamed column.` });
      } else if (seenCols.has(colKey)) {
        issues.push({ level: "error", entity_id: ent.id, message: `Duplicate column "${f.name}" in "${ent.name}".` });
      }
      seenCols.add(colKey);
    }
  }

  for (const rel of relationships) {
    const src = entityMap.get(rel.source_entity);
    const tgt = entityMap.get(rel.target_entity);
    if (!src || !tgt) {
      issues.push({ level: "warning", entity_id: rel.source_entity, message: "A relationship references a deleted table." });
    }
  }

  return issues;
}

export function generateSql(schemaContent) {
  const entities = schemaContent?.entities || [];
  const relationships = schemaContent?.relationships || [];

  if (!entities.length) return "-- No entities defined in schema.";

  let sql = '-- Generated by Blueprint OS (PostgreSQL)\nCREATE EXTENSION IF NOT EXISTS "pgcrypto";\n\n';

  const entityMap = new Map();
  const fieldMap = new Map();

  for (const ent of entities) {
    entityMap.set(ent.id, ent);
    for (const f of ent.fields || []) {
      fieldMap.set(f.id, { field: f, entity: ent });
    }
  }

  for (const ent of entities) {
    const tableName = (ent.name || "unnamed_table").toLowerCase().replace(/[^a-z0-9_]+/g, "_");
    if (ent.purpose) {
      sql += `-- ${ent.purpose}\n`;
    }
    sql += `CREATE TABLE "${tableName}" (\n`;
    const colLines = [];

    const fields = ent.fields || [];
    for (const f of fields) {
      const colName = (f.name || "col").toLowerCase().replace(/[^a-z0-9_]+/g, "_");
      let colType = f.type ? f.type.toUpperCase() : "VARCHAR(255)";
      if (colType === "UUID" && f.primary_key) {
        colType = "UUID NOT NULL DEFAULT gen_random_uuid()";
      } else if (!f.nullable) {
        colType += " NOT NULL";
      }
      if (f.default && !f.primary_key) {
        colType += ` DEFAULT ${f.default}`;
      }
      if (f.unique && !f.primary_key) {
        colType += " UNIQUE";
      }
      colLines.push(`  "${colName}" ${colType}`);
    }

    if (ent.timestamps !== false) {
      colLines.push('  "created_at" TIMESTAMPTZ NOT NULL DEFAULT now()');
      colLines.push('  "updated_at" TIMESTAMPTZ NOT NULL DEFAULT now()');
    }

    const pkField = fields.find((f) => f.primary_key) || { name: "id" };
    colLines.push(`  PRIMARY KEY ("${pkField.name}")`);

    sql += colLines.join(",\n");
    sql += "\n);\n\n";
  }

  // Relationships / Foreign keys
  for (const rel of relationships) {
    const srcEnt = entityMap.get(rel.source_entity) || entities.find((e) => e.name === rel.from_table);
    const tgtEnt = entityMap.get(rel.target_entity) || entities.find((e) => e.name === rel.to_table);
    const srcFld = fieldMap.get(rel.source_field)?.field || srcEnt?.fields?.find((f) => f.name === rel.from_field);
    const tgtFld = fieldMap.get(rel.target_field)?.field || tgtEnt?.fields?.find((f) => f.primary_key);

    if (srcEnt && tgtEnt && srcFld) {
      const fromTable = srcEnt.name.toLowerCase().replace(/[^a-z0-9_]+/g, "_");
      const toTable = tgtEnt.name.toLowerCase().replace(/[^a-z0-9_]+/g, "_");
      const fromCol = srcFld.name.toLowerCase().replace(/[^a-z0-9_]+/g, "_");
      const toCol = (tgtFld?.name || "id").toLowerCase().replace(/[^a-z0-9_]+/g, "_");
      const fkName = `fk_${fromTable}_${fromCol}`;
      const onDelete = (rel.on_delete || "CASCADE").toUpperCase();
      sql += `ALTER TABLE "${fromTable}" ADD CONSTRAINT "${fkName}" FOREIGN KEY ("${fromCol}") REFERENCES "${toTable}"("${toCol}") ON DELETE ${onDelete};\n`;
    }
  }

  // Indexes
  for (const ent of entities) {
    const tableName = ent.name.toLowerCase().replace(/[^a-z0-9_]+/g, "_");
    for (const f of ent.fields || []) {
      if ((f.indexed || f.name.endsWith("_id")) && !f.primary_key) {
        const colName = f.name.toLowerCase().replace(/[^a-z0-9_]+/g, "_");
        sql += `CREATE INDEX "idx_${tableName}_${colName}" ON "${tableName}" ("${colName}");\n`;
      }
    }
  }

  return sql;
}

export function generatePrisma(schemaContent) {
  const entities = schemaContent?.entities || [];
  if (!entities.length) return "// No entities defined";

  let prisma = `// Generated by Blueprint OS
generator client {
  provider = "prisma-client-js"
}

datasource db {
  provider = "postgresql"
  url      = env("DATABASE_URL")
}
\n`;

  const typeMap = {
    uuid: "String @db.Uuid",
    text: "String",
    "varchar(255)": "String",
    "varchar(120)": "String",
    "varchar(100)": "String",
    "varchar(50)": "String",
    "varchar(20)": "String",
    varchar: "String",
    integer: "Int",
    int: "Int",
    bigint: "BigInt",
    boolean: "Boolean",
    "numeric(10,2)": "Decimal @db.Decimal(10,2)",
    "numeric(12,2)": "Decimal @db.Decimal(12,2)",
    decimal: "Decimal @db.Decimal(10,2)",
    timestamptz: "DateTime @db.Timestamptz",
    timestamp: "DateTime @db.Timestamptz",
    date: "DateTime @db.Date",
    jsonb: "Json",
  };

  const toPascal = (s) =>
    (s || "Model")
      .split(/[^a-zA-Z0-9]+/)
      .filter(Boolean)
      .map((w) => w.charAt(0).toUpperCase() + w.slice(1))
      .join("");

  for (const ent of entities) {
    const pascalName = toPascal(ent.name);
    prisma += `model ${pascalName} {\n`;
    for (const f of ent.fields || []) {
      const propName = f.name;
      const lowerType = (f.type || "").toLowerCase();
      let pType = typeMap[lowerType] || (lowerType.startsWith("varchar") ? "String" : lowerType.startsWith("numeric") ? "Decimal @db.Decimal(10,2)" : "String");
      let modifiers = "";
      if (f.primary_key) {
        modifiers += " @id @default(uuid())";
      }
      if (f.unique && !f.primary_key) {
        modifiers += " @unique";
      }
      if (f.nullable && !f.primary_key) {
        pType = `${pType.split(" ")[0]}?${pType.includes("@") ? " " + pType.slice(pType.indexOf("@")) : ""}`;
      }
      prisma += `  ${propName} ${pType}${modifiers}\n`;
    }
    if (ent.timestamps !== false) {
      prisma += `  createdAt DateTime @default(now()) @map("created_at") @db.Timestamptz\n`;
      prisma += `  updatedAt DateTime @updatedAt @map("updated_at") @db.Timestamptz\n`;
    }
    prisma += `  @@map("${ent.name.toLowerCase()}")\n`;
    prisma += `}\n\n`;
  }

  return prisma;
}

